// Builds tokens/tokens.css (and the theme item in registry.json) from tokens/tokens.json.
// Semantic colours are written as bare HSL channels ("40 18% 3%") so Tailwind's
// opacity modifiers work: bg-primary/90 → hsl(var(--primary) / 0.9).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const tokens = JSON.parse(readFileSync(`${root}tokens/tokens.json`, 'utf8'));

const isMeta = (key) => key.startsWith('$');
const entries = (group) => Object.entries(group).filter(([key]) => !isMeta(key));

function hexToHsl(hex) {
  const n = parseInt(hex.slice(1), 16);
  const [r, g, b] = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map((v) => v / 255);
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  let h = 0;
  let s = 0;
  if (max !== min) {
    const d = max - min;
    s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
    if (max === r) h = (g - b) / d + (g < b ? 6 : 0);
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h *= 60;
  }
  const round = (v) => Math.round(v * 10) / 10;
  return `${round(h)} ${round(s * 100)}% ${round(l * 100)}%`;
}

function resolve(ref) {
  const match = /^\{color\.(.+)\}$/.exec(ref);
  if (!match) throw new Error(`Unsupported reference: ${ref}`);
  const token = tokens.color[match[1]];
  if (!token) throw new Error(`Unknown colour: ${ref}`);
  return token.$value;
}

const cssValue = (value) =>
  Array.isArray(value)
    ? typeof value[0] === 'number'
      ? `cubic-bezier(${value.join(', ')})`
      : value.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', ')
    : value;

const block = (selector, lines) => `${selector} {\n${lines.map((l) => `  ${l}`).join('\n')}\n}\n`;

const semantic = (mode) =>
  Object.fromEntries(entries(tokens.semantic[mode]).map(([name, ref]) => [name, hexToHsl(resolve(ref))]));
const light = semantic('light');
const dark = semantic('dark');

const rootLines = [
  '/* Palette — raw hex, for one-off use. Prefer the semantic roles below. */',
  ...entries(tokens.color).map(([name, t]) => `--gc-${name}: ${t.$value};`),
  '',
  '/* Semantic roles (HSL channels) */',
  ...Object.entries(light).map(([name, v]) => `--${name}: ${v};`),
  '',
  '/* Type */',
  ...entries(tokens.font.family).map(([name, t]) => `--font-${name}: ${cssValue(t.$value)};`),
  ...entries(tokens.font.weight).map(([name, t]) => `--font-weight-${name}: ${t.$value};`),
  ...entries(tokens.font.size).map(([name, t]) => `--text-${name}: ${t.$value};`),
  '',
  '/* Shape, depth, motion */',
  `--radius: ${tokens.radius.lg.$value};`,
  ...entries(tokens.radius).map(([name, t]) => `--radius-${name}: ${t.$value};`),
  ...entries(tokens.shadow).map(([name, t]) => `--shadow-${name}: ${t.$value};`),
  ...entries(tokens.motion.easing).map(([name, t]) => `--ease-${name}: ${cssValue(t.$value)};`),
  ...entries(tokens.motion.duration).map(([name, t]) => `--duration-${name}: ${t.$value};`),
];

const css = [
  '/* GoodCart tokens — generated by scripts/build-tokens.mjs from tokens.json. Do not edit by hand. */\n',
  block(':root', rootLines),
  '/* Dark theme (draft) — add class="dark" to <html> */',
  block('.dark', Object.entries(dark).map(([name, v]) => `--${name}: ${v};`)),
].join('\n');

writeFileSync(`${root}tokens/tokens.css`, css);

// Keep the shadcn registry theme in sync so `shadcn add <url>/r/goodcart-theme.json` installs these tokens
const registryPath = `${root}registry.json`;
const registry = JSON.parse(readFileSync(registryPath, 'utf8'));
const theme = registry.items.find((item) => item.name === 'goodcart-theme');
if (theme) {
  theme.cssVars = { theme: { radius: tokens.radius.lg.$value }, light, dark };
  writeFileSync(registryPath, `${JSON.stringify(registry, null, 2)}\n`);
}

console.log(`tokens.css: ${Object.keys(light).length} semantic roles, ${entries(tokens.color).length} palette colours`);
